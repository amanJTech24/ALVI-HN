"""
ALVI MindPlay Cognitive Games Routes
Provides endpoints for:
- MindPlay challenges catalog and rules
- Empirical game submission and deterministic scoring
- Multi-session personalized longitudinal analytics
"""

import logging
from typing import Any, Dict, List, Optional

from fastapi import APIRouter, HTTPException, status
from pydantic import BaseModel, Field

from backend.services.game_analytics import MindPlayAnalyticsService
from backend.services.game_scoring import (
    MindPlayScoringService,
    get_game_config,
)

logger = logging.getLogger("alvi.games")

router = APIRouter(prefix="/api/games", tags=["MindPlay Games"])

_scoring_service = MindPlayScoringService()
_analytics_service = MindPlayAnalyticsService()


class MindPlaySubmission(BaseModel):
    session_id: Optional[str] = Field(
        default=None,
        description="Session identifier generated by client."
    )
    ch1_selected: List[str] = Field(
        default_factory=list,
        description="Selected items in Challenge 1 (Remember)."
    )
    ch2_sequence: List[Any] = Field(
        default_factory=list,
        description="Event IDs in participant's final order for Challenge 2 (Sequence)."
    )
    ch3_selected: Optional[str] = Field(
        default=None,
        description="Selected card key in Challenge 3 (Find)."
    )
    ch3_reaction_ms: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=120000.0,
        description="High-resolution reaction latency in milliseconds."
    )
    total_time_seconds: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=3600.0,
        description="Total duration elapsed across MindPlay challenges in seconds."
    )
    interaction_metadata: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional telemetry metadata (e.g. move counts, toggles)."
    )


class MindPlayHistoryRequest(BaseModel):
    sessions: List[Dict[str, Any]] = Field(
        ...,
        description="List of prior completed MindPlay session records."
    )


@router.get("/catalog")
def get_games_catalog() -> Dict[str, Any]:
    """
    Retrieve the catalog of MindPlay challenges with rules, targets, and scoring weights.
    """
    cfg = get_game_config()
    return {
        "status": "success",
        "version": cfg.get("version", "1.0.0"),
        "task_name": cfg.get("task_name", "MindPlay Tri-Challenge Cognitive Assessment"),
        "narrative_context": cfg.get("narrative_context", "aarav_story_v1"),
        "challenges": cfg.get("challenges", {}),
        "composite_weights": cfg.get("composite_weights", {}),
        "performance_bands": cfg.get("performance_bands", [])
    }


@router.post("/submit")
def submit_mindplay_results(payload: MindPlaySubmission) -> Dict[str, Any]:
    """
    Evaluate participant empirical interactions across the three MindPlay challenges:
    1. Challenge 1 (Remember): Target recognition & distractor error filtering
    2. Challenge 2 (Sequence): Kendall tau temporal inversion scoring
    3. Challenge 3 (Find): Visual target discrimination & high-resolution latency scoring
    4. Deterministic composite performance calculation with qualitative feedback
    """
    try:
        result = _scoring_service.score_session(
            ch1_selected=payload.ch1_selected,
            final_sequence=payload.ch2_sequence,
            ch3_selected=payload.ch3_selected,
            ch3_reaction_ms=payload.ch3_reaction_ms,
            total_time_seconds=payload.total_time_seconds,
            session_id=payload.session_id
        )

        # Attach interaction metadata if provided
        if payload.interaction_metadata:
            result["interaction_metadata"] = payload.interaction_metadata

        return {
            "status": "success",
            "data": result
        }

    except Exception as exc:
        logger.exception("Error scoring MindPlay submission: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"MindPlay scoring error: {str(exc)}"
        )


@router.post("/analyze-history")
def analyze_mindplay_history(payload: MindPlayHistoryRequest) -> Dict[str, Any]:
    """
    Compute within-participant personalized baseline and trajectory metrics
    across repeated MindPlay session attempts.
    """
    try:
        analytics = _analytics_service.analyze_history(payload.sessions)
        return {
            "status": "success",
            "data": analytics
        }
    except Exception as exc:
        logger.exception("Error analyzing MindPlay history: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"MindPlay history analysis error: {str(exc)}"
        )

